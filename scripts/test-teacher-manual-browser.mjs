import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.KLINK_TEST_URL || 'http://127.0.0.1:5208';
const out = process.env.KLINK_MANUAL_OUTPUT || 'outputs/manual-wiki-20261018';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage();
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const chapters = JSON.parse(readFileSync('data/klink-teacher-manual.json', 'utf8'));
try {
  await page.setViewportSize({ width: 1440, height: 1000 });
  for (const chapter of chapters) {
    await page.goto(`${base}/docenten/${chapter.id}`);
    await page.getByRole('heading', { name: chapter.title.replace(/^\d+ /, ''), exact: true }).waitFor();
    assert.equal(await page.locator('h1').count(), 1);
    assert.equal(await page.locator('.wiki-article').count(), 1);
    assert.equal(await page.locator('.wiki-article h2').count(), (chapter.html.match(/<h3>/g) || []).length);
    assert.equal(await page.locator('.wiki-desktop-navigation [aria-current="page"]').getAttribute('href'), `/docenten/${chapter.id}`);
    const actual = await page.locator('.wiki-article > div').textContent();
    const expected = await page.evaluate(html => { const element = document.createElement('div'); element.innerHTML = html; return element.textContent; }, chapter.html);
    assert.equal(actual, expected, `${chapter.id}: reviewed source text rendered`);
    assert.equal(await page.title(), `${chapter.title.replace(/^\d+ /, '')} | Klink docentenhandleiding`);
  }
  checks.push('All twelve direct chapter URLs return exactly the reviewed article text, one article, a matching title and active navigation.');
  for (const width of [1440, 820, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(base);
    await page.getByRole('link', { name: 'Voor docenten', exact: true }).click();
    await page.getByRole('heading', { name: 'Docentenhandleiding', exact: true }).waitFor();
    assert.equal(await page.locator('.wiki-article').count(), 0);
    assert.equal(await page.locator('.wiki-topic-groups a').count(), 12);
    assert((await page.locator('main').innerText()).split(/\s+/).length < 200, 'Overview stays compact');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `${out}/wiki-overview-${width}.png` });
    if (width <= 850) {
      const menu = page.locator('.wiki-mobile-navigation');
      assert.equal(await menu.getAttribute('open'), null);
      await menu.locator('summary').focus(); await page.keyboard.press('Enter');
      await menu.getByRole('link', { name: 'Een oefenblok met mat', exact: true }).click();
      await page.getByRole('heading', { name: 'Een oefenblok met mat', exact: true }).waitFor();
      assert.equal(await menu.getAttribute('open'), null, 'Menu closes after choosing a topic');
    } else await page.locator('.wiki-topic-groups').getByRole('link', { name: 'Een oefenblok met mat', exact: true }).click();
    await page.getByRole('heading', { name: 'Een oefenblok met mat', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Een oefenblok met mat', exact: true }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `${out}/wiki-article-${width}.png` });
    await page.getByRole('navigation', { name: 'Verder in de handleiding' }).getByRole('link', { name: /Volgend onderwerp/ }).click();
    await page.getByRole('heading', { name: 'Individueel en samen oefenen', exact: true }).waitFor();
    assert(await page.evaluate(() => scrollY < 100), 'New article opens at its beginning');
    await page.goBack();
    await page.getByRole('heading', { name: 'Een oefenblok met mat', exact: true }).waitFor();
    await page.getByRole('navigation', { name: 'Kruimelpad' }).getByRole('link', { name: 'Docentenhandleiding', exact: true }).click();
    await page.getByRole('link', { name: 'Open de docentomgeving', exact: true }).click();
    await page.locator('.staff-app').waitFor();
    await page.getByRole('link', { name: 'Voor docenten', exact: true }).click();
    await page.getByRole('link', { name: 'Naar Klink', exact: true }).click();
    await page.locator('.cp-home').waitFor();
    checks.push(`${width}px: compact overview, topic selection, reload, next/back, return to teacher/learner, no page overflow.`);
  }
  await page.goto(`${base}/docenten#hoofdstuk-5`);
  await page.waitForURL('**/docenten/hoofdstuk-5');
  await page.getByRole('heading', { name: 'Een oefenblok met mat', exact: true }).waitFor();
  await page.goto(`${base}/docenten/hoofdstuk-1`);
  await page.locator('.wiki-article').getByRole('link', { name: 'hoofdstuk 10', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Je les voorbereiden', exact: true }).waitFor();
  const missing = await page.goto(`${base}/docenten/hoofdstuk-99`);
  assert.equal(missing.status(), 404);
  await page.getByRole('heading', { name: 'Onderwerp niet gevonden', exact: true }).waitFor();
  checks.push('Existing chapter bookmarks, internal chapter links and unknown-topic recovery work.');
  await page.setViewportSize({ width: 844, height: 390 });
  await page.goto(`${base}/#learner/packages`);
  await page.locator('.cp-package-grid > button').first().click();
  await page.locator('.cp-tabs').getByRole('button', { name: 'Stap voor stap', exact: true }).click();
  await page.locator('.cp-start-lesson').first().click();
  await page.locator('.cp-exercise-browser.is-guided').waitFor();
  assert(await page.locator('.taalroute-header').isHidden());
  await page.locator('.cp-lesson-player > .text-back').click();
  assert(await page.getByRole('link', { name: 'Voor docenten', exact: true }).isVisible());
  checks.push('Short guided lesson retains its reading space; leaving restores the teacher entry.');
  assert.deepEqual(errors, []);
  writeFileSync(`${out}/wiki-${base.startsWith('https') ? 'live' : 'local'}.json`, JSON.stringify({ base, checkedAt: new Date().toISOString(), checks, errors }, null, 2));
  console.log('PASS wiki:', checks.join('\n'));
} catch (error) {
  console.log({ url: page.url(), viewport: page.viewportSize(), headings: await page.locator('h1').allTextContents(), errors });
  await page.screenshot({ path: `${out}/failure.png` });
  throw error;
} finally { await browser.close(); }
