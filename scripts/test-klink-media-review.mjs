import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { taalroutePackages as packs } from '../lib/taalroute-packages.ts';
const out = 'outputs/media-review-20261016';
const manifest = JSON.parse(readFileSync(`${out}/review-manifest.json`));
const batch = JSON.parse(readFileSync('docs/klink-beeldbatch-20261016.json'));
const sha = file => createHash('sha256').update(readFileSync(file)).digest('hex');
for (const item of manifest.items) assert.equal(sha(`${out}/${item.path}`), item.sha256);
assert.equal(manifest.publicationApproved, false);
assert.equal(manifest.items.filter(item => item.group === 'Nieuwe beelden').length, 16);
assert.equal(manifest.missingImages.length, 161);
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const reviewUrl = pathToFileURL(resolve(`${out}/index.html`)).href;
try {
  await page.goto(reviewUrl);
  assert(await page.locator('#approve').isDisabled());
  await page.locator('#reviewer').fill('Automatische test — geen menselijke goedkeuring');
  assert(await page.locator('#approve').isEnabled());
  await page.locator('#media img').dispatchEvent('error');
  assert(await page.locator('#approve').isDisabled());
  await page.locator('#media img').dispatchEvent('load');
  assert(await page.locator('#approve').isEnabled());
  await page.locator('#approve').click();
  assert.equal(await page.locator('#counter').innerText(), '2 van 16');
  await page.locator('#group').selectOption('Nieuwe woordaudio');
  assert(await page.locator('#approve').isDisabled());
  await page.locator('audio').evaluate(audio => audio.play());
  await page.waitForFunction(() => !document.querySelector('#approve').disabled);
  await page.locator('#approve').click();
  assert(await page.locator('#approve').isDisabled());
  await page.locator('#repair').click();
  assert((await page.locator('#item-status').innerText()).includes('Schrijf kort'));
  await page.locator('#comment').fill('Testmelding, geen inhoudelijke beoordeling.');
  await page.locator('#repair').click();
  const downloadWait = page.waitForEvent('download');
  await page.locator('#download').click();
  const downloaded = await downloadWait;
  const exported = JSON.parse(readFileSync(await downloaded.path()));
  assert.equal(exported.decisions.length, 3);
  assert.equal(exported.publicationApproved, false);
  assert(exported.decisions.every(item => /^[a-f0-9]{64}$/.test(item.sha256)));
  assert(exported.decisions.find(item => item.id.startsWith('audio:') && item.status === 'approved').playedToEnd);
  await page.reload();
  assert((await page.locator('#total').innerText()).startsWith('3 van'));
  await page.evaluate(() => { const key = 'klink.media-review.20261016', data = JSON.parse(localStorage.getItem(key)); Object.values(data.decisions).forEach(item => item.sha256 = 'outdated'); localStorage.setItem(key, JSON.stringify(data)); });
  await page.reload();
  assert((await page.locator('#total').innerText()).startsWith('0 van'));
  checks.push('Review needs a reviewer name, actual audio completion, a separate explicit choice and exact file hashes; export never grants publication.');
  await page.evaluate(() => localStorage.clear());
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 900 }); await page.goto(reviewUrl);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `${out}/beoordeling-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1280, height: 1300 });
  await page.goto(pathToFileURL(resolve(`${out}/contactblad.html`)).href);
  await page.waitForFunction(() => [...document.images].every(image => image.complete && image.naturalWidth));
  await page.screenshot({ path: `${out}/contactblad.png`, fullPage: true });
  checks.push('All sixteen delivery images appear without cropping on the contact sheet; review fits desktop and narrow screens.');
  const app = await browser.newPage({ viewport: { width: 1366, height: 900 } });
  app.on('pageerror', error => errors.push(error.message));
  const base = process.env.KLINK_TEST_URL || 'http://127.0.0.1:18816';
  for (const item of batch.items) {
    const pack = packs.find(pack => pack.exercises.some(exercise => exercise.mode === 'model' && exercise.wordId === item.id));
    const exercise = pack.exercises.find(exercise => exercise.mode === 'model' && exercise.wordId === item.id);
    await app.goto(`${base}/#learner/home`);
    await app.evaluate(position => localStorage.setItem('klink.taalroute.route.v1', JSON.stringify({ position, completed: [] })), { packageId: pack.id, lessonId: exercise.lessonId, exerciseId: exercise.exerciseId });
    await app.reload(); await app.getByRole('button', { name: 'Ga verder', exact: true }).click();
    await app.waitForFunction(() => document.querySelector('.cp-model-content img')?.naturalWidth > 0);
    const imageUrl = new URL(await app.locator('.cp-model-content img').getAttribute('src'), base);
    assert.equal(imageUrl.pathname === '/_next/image' ? imageUrl.searchParams.get('url') : imageUrl.pathname, item.image);
    assert.equal(await app.locator('.cp-model-content img').evaluate(img => getComputedStyle(img).objectFit), 'contain');
  }
  checks.push('Every new word image is bound to its exact meaning in the existing Klink player; app routes and image proportions stay intact.');
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
writeFileSync(`${out}/browser-check.json`, JSON.stringify({ checks, errors, humanReview: 'open' }, null, 2));
console.log(checks.join('\n'));
