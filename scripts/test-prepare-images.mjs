import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, copyFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { prepareImages, imageBudget } from './prepare-images.mjs';

const root = mkdtempSync(join(tmpdir(), 'klink-images-'));
const put = (path, bytes) => writeFileSync(join(root, path), bytes);
const json = path => JSON.parse(readFileSync(join(root, path), 'utf8'));
try {
  for (const dir of ['public/handschrift', 'data', 'lib', 'docs/image-size-audit-20261031']) mkdirSync(join(root, dir), { recursive: true });
  for (const file of ['data/klink-compact-images-20261031.json', 'data/klink-image-preparation.json']) put(file, '{}\n');
  for (const file of ['assets', 'inventory']) put('docs/image-size-audit-20261031/' + file + '.json', '[]');
  const large = await sharp(randomBytes(1800 * 1200 * 3), { raw: { width: 1800, height: 1200, channels: 3 } }).png().toBuffer();
  put('public/new.png', large);
  await assert.rejects(prepareImages(root, { check: true }), /eerst worden verkleind/);
  const result = await prepareImages(root);
  assert.equal(result.prepared, 1);
  assert.deepEqual(readFileSync(join(root, 'public/new.png')), large, 'Original is preserved');
  const map = json('data/klink-compact-images-20261031.json');
  const output = readFileSync(join(root, 'public', map['/new.png']));
  assert(output.length < large.length / 10 && output.length <= imageBudget);
  const size = await sharp(output).metadata();
  assert.equal(size.width, 640); assert(Math.abs(size.width / size.height - 1.5) < .01);
  const modified = statSync(join(root, 'public', map['/new.png'])).mtimeMs;
  assert.equal((await prepareImages(root)).prepared, 0);
  const tinyLarge = await sharp({ create: { width: 2000, height: 2000, channels: 3, background: '#abcdef' } }).avif({ quality: 20 }).toBuffer();
  put('public/tiny-large.avif', tinyLarge);
  await prepareImages(root);
  assert.equal(json('data/klink-image-preparation.json')['/tiny-large.avif'].width, 640, 'Tiny file size cannot retain unnecessarily large decoded dimensions');
  assert.equal(statSync(join(root, 'public', map['/new.png'])).mtimeMs, modified);
  await prepareImages(root, { check: true });
  copyFileSync('lib/compact-images.ts', join(root, 'lib/compact-images.ts'));
  const { compactImageSrc } = await import(pathToFileURL(join(root, 'lib/compact-images.ts')));
  assert.equal(compactImageSrc('/new.png'), map['/new.png'], 'The real app resolver uses the new derivative');
  put('public' + map['/new.png'], Buffer.from('damaged'));
  await assert.rejects(prepareImages(root, { check: true }), /Veranderd compact bestand|Beschadigd compact beeld/);
  put('public' + map['/new.png'], output);
  const small = await sharp({ create: { width: 64, height: 64, channels: 3, background: '#abc' } }).png().toBuffer();
  put('public/new.png', small);
  await assert.rejects(prepareImages(root, { check: true }), /Gewijzigde bron/);
  await prepareImages(root);
  assert(!json('data/klink-compact-images-20261031.json')['/new.png'], 'A smaller replacement cannot retain a stale image mapping');
  await prepareImages(root, { check: true });
  assert.equal((await prepareImages(root)).prepared, 0);
  const text = await sharp({ create: { width: 2000, height: 500, channels: 3, background: '#fff' } }).composite([{ input: Buffer.from('<svg width="2000" height="500"><text x="20" y="300" font-size="180">Leesbaar woord</text></svg>') }]).png().toBuffer();
  put('public/handschrift/word.png', text);
  await prepareImages(root);
  const handwriting = json('data/klink-image-preparation.json')['/handschrift/word.png'];
  assert.equal(handwriting.width, 1280); assert.equal(handwriting.height, 320);
  const vector = '<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><!--' + 'x'.repeat(imageBudget) + '--><path d="M0 0h20v20"/></svg>';
  put('public/logo.svg', vector);
  await assert.rejects(prepareImages(root), /groter dan 96 KiB/);
  assert.equal(readFileSync(join(root, 'public/logo.svg'), 'utf8'), vector, 'Do not rasterize or rewrite vector lettering');
  rmSync(join(root, 'public/logo.svg'));
  put('public/broken.png', 'invalid image');
  await assert.rejects(prepareImages(root));
  console.log('PASS automatic preparation, budget, original/aspect/text preservation, real resolver, idempotence, stale/corrupt inputs and oversized vector rejection');
} finally { rmSync(root, { recursive: true, force: true }); }
