import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { taalroutePackages as packs } from '../lib/taalroute-packages.ts';
import { groupExercises } from '../lib/group-practice.ts';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.KLINK_TEST_URL || 'http://127.0.0.1:18816';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
const checks = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => {
  window.__started = [];
  window.__rates = [];
  const original = Object.getOwnPropertyDescriptor(HTMLMediaElement.prototype, 'play').value;
  HTMLMediaElement.prototype.play = function (...args) {
    window.__rates.push({ rate: this.playbackRate, defaultRate: this.defaultPlaybackRate, pitch: this.preservesPitch });
    this.addEventListener('playing', () => window.__started.push(this.src), { once: true });
    return original.apply(this, args);
  };
});
try {
  await page.goto(`${base}/#learner/home`);
  await page.getByRole('navigation', { name: 'Cursistnavigatie' }).getByRole('button', { name: 'Lessen', exact: true }).click();
  await page.locator('.cp-package-grid > button').nth(2).click();
  await page.locator('.cp-tabs').getByRole('button', { name: 'Samen oefenen', exact: true }).click(); await page.locator('.cp-step-scope select').selectOption('');
  await page.locator('[data-activity="meet"]').click();
  const id = await page.locator('.cp-exercise-browser').getAttribute('data-exercise-id');
  const model = groupExercises(packs[2], 'meet').find(item => item.exerciseId === id);
  await page.waitForFunction(src => window.__started.some(path => path.endsWith(src)), model.prompt.audio.src, { timeout: 20000 });
  checks.push('Free-practice model starts the word recording directly, without spoken instructions');
  await page.getByRole('button', { name: 'Alle oefeningen', exact: true }).first().click();
  await page.locator('[data-activity="write"]').click();
  const writingId = await page.locator('.cp-exercise-browser').getAttribute('data-exercise-id');
  const writing = groupExercises(packs[2], 'write').find(item => item.exerciseId === writingId);
  assert.equal(await page.getByRole('button', { name: 'Luister naar de opdracht', exact: true }).count(), 0);
  await page.evaluate(() => { window.__started = []; });
  await page.getByRole('button', { name: 'Luister naar het woord', exact: true }).click();
  await page.waitForFunction(src => window.__started.some(path => path.endsWith(src)), writing.prompt.audio.src, { timeout: 20000 });
  checks.push('The writing button plays the actual matching word file');
  await page.getByRole('button', { name: 'Alle oefeningen', exact: true }).first().click();
  const heard = groupExercises(packs[2], 'hear-word')[0];
  await page.route(`**${heard.prompt.audio.src}`, route => route.abort());
  await page.locator('[data-activity="hear-word"]').click();
  await page.getByText('Probeer Luister opnieuw', { exact: true }).waitFor({ timeout: 20000 });
  assert(await page.locator('.cp-choice-grid button').first().isDisabled());
  await page.unroute(`**${heard.prompt.audio.src}`);
  await page.getByRole('button', { name: 'Opnieuw luisteren', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.cp-choice-grid button')?.disabled, undefined, { timeout: 20000 });
  assert.equal(await page.locator('.cp-audio-retry').count(), 0);
  checks.push('Failed automatic playback exposes a working retry and does not unlock listening answers early');
  await page.getByRole('button', { name: 'Alle oefeningen', exact: true }).first().click();
  await page.locator('[data-activity="speak"]').click();
  await page.getByRole('button', { name: 'Neem op', exact: true }).click();
  await page.getByRole('button', { name: 'Stop', exact: true }).waitFor();
  await page.waitForTimeout(400);
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  const recording = page.locator('audio[aria-label="Jouw opname"]');
  await recording.waitFor();
  assert.deepEqual(await recording.evaluate(audio => ({ rate: audio.playbackRate, defaultRate: audio.defaultPlaybackRate, pitch: audio.preservesPitch })), { rate: .85, defaultRate: .85, pitch: true });
  await page.goto(`${base}/#teacher`);
  await page.locator('.staff-nav').getByRole('button', { name: 'Media', exact: true }).click();
  await page.getByLabel('Zoek tekst of audio-ID').fill('vraag-biet');
  await page.locator('tr[data-audio-id="vraag-biet"]').getByRole('button').click();
  const rates = await page.evaluate(() => window.__rates);
  assert(rates.length >= 4);
  assert((await page.evaluate(() => window.__started)).every(source => !source.includes('/instructions/')));
  assert(rates.every(item => item.rate === .85 && item.defaultRate === .85 && item.pitch === true));
  checks.push('Actual task, word, retry and teacher playback use 0.85; instructions stay silent; learner recording controls also default to 0.85');
  assert.deepEqual(errors, []);
} finally {
  mkdirSync('outputs/ux-review-20261017', { recursive: true });
  writeFileSync('outputs/ux-review-20261017/real-audio-check.json', JSON.stringify({ base, checks, errors }, null, 2));
  await browser.close();
}
console.log(checks.map(check => `PASS ${check}`).join('\n'));
